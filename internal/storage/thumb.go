const (
	thumbWidth  = 640
	thumbHeight = 400
)

// GenerateThumbnail builds a PNG preview card for a dashboard title.
// Used when uploads omit a client-provided thumbnail.
func GenerateThumbnail(title string) ([]byte, error) {
	title = strings.TrimSpace(title)
	if title == "" {
		title = "Untitled Dashboard"
	}
	if len([]rune(title)) > 42 {
		r := []rune(title)
		title = string(r[:39]) + "..."
	}

	img := image.NewRGBA(image.Rect(0, 0, thumbWidth, thumbHeight))
	bg := color.RGBA{R: 232, G: 237, B: 242, A: 255}
	header := color.RGBA{R: 15, G: 118, B: 110, A: 255}
	headerText := color.RGBA{R: 255, G: 255, B: 255, A: 255}
	bodyText := color.RGBA{R: 90, G: 111, B: 130, A: 255}
	card := color.RGBA{R: 255, G: 255, B: 255, A: 255}
	border := color.RGBA{R: 203, G: 213, B: 225, A: 255}

	fillRect(img, 0, 0, thumbWidth, thumbHeight, bg)
	fillRect(img, 0, 0, thumbWidth, 64, header)

	// Content card
	const cardX, cardY, cardW, cardH = 32, 96, 576, 240
	fillRect(img, cardX, cardY, cardW, cardH, card)
	strokeRect(img, cardX, cardY, cardW, cardH, border)

	drawText(img, 28, 24, title, headerText, 2)
	drawText(img, cardX+24, cardY+28, "Dashboard preview", bodyText, 2)

	// Decorative preview lines inside the card
	line := color.RGBA{R: 226, G: 232, B: 240, A: 255}
	accent := color.RGBA{R: 153, G: 246, B: 228, A: 255}
	for i := 0; i < 5; i++ {
		y := cardY + 80 + i*28
		w := 420 - i*36
		if w < 120 {
			w = 120
		}
		c := line
		if i == 0 {
			c = accent
			w = 180
		}
		fillRect(img, cardX+24, y, w, 12, c)
	}

	var buf bytes.Buffer
	if err := png.Encode(&buf, img); err != nil {
		return nil, err
	}
	return buf.Bytes(), nil
}

func fillRect(img *image.RGBA, x, y, w, h int, c color.RGBA) {
	for yy := y; yy < y+h; yy++ {
		for xx := x; xx < x+w; xx++ {
			img.SetRGBA(xx, yy, c)
		}
	}
}

func strokeRect(img *image.RGBA, x, y, w, h int, c color.RGBA) {
	for xx := x; xx < x+w; xx++ {
		img.SetRGBA(xx, y, c)
		img.SetRGBA(xx, y+h-1, c)
	}
	for yy := y; yy < y+h; yy++ {
		img.SetRGBA(x, yy, c)
		img.SetRGBA(x+w-1, yy, c)
	}
}

// drawText renders title text with a scaled 5x7 bitmap font.
func drawText(img *image.RGBA, x, y int, text string, c color.RGBA, scale int) {
	if scale < 1 {
		scale = 1
	}
	cx := x
	for _, r := range text {
		glyph, ok := font5x7[r]
		if !ok {
			glyph = font5x7['?']
		}
		for row := 0; row < 7; row++ {
			bits := glyph[row]
			for col := 0; col < 5; col++ {
				if bits&(1<<uint(4-col)) == 0 {
					continue
				}
				for sy := 0; sy < scale; sy++ {
					for sx := 0; sx < scale; sx++ {
						img.SetRGBA(cx+col*scale+sx, y+row*scale+sy, c)
					}
				}
			}
		}
		cx += 6 * scale
		if cx > thumbWidth-12 {
			break
		}
	}
}

